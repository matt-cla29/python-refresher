print("\n--- COMPARISON OPERATORS ---")

# Comparison operators are used to compare two values and return a boolean (True or False) result.
# The basic comparison operators in Python are:
# Equal to (==), Not equal to (!=), Greater than (>), Less than (<),
# Greater than or equal to (>=), Less than or equal to (<=)
# Comparison operators are often used in conditional statements (like if statements) to make decisions.

num1 = 10
num2 = 5

print("Equal to:", num1 == num2)           # Checks if values are equal
print("Not equal to:", num1 != num2)       # Checks if values are different (not equal)
print("Greater than:", num1 > num2)        # Is num1 bigger than num2? (greater than)
print("Less than:", num1 < num2)           # Is num1 smaller than num2? (less than)
print("Greater or equal:", num1 >= num2)   # Bigger OR same? (greater than OR equal to)
print("Less or equal:", num1 <= num2)      # Smaller OR same? (less than OR equal to)

print("\n------------------------------\n")
